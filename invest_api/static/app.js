  function effectivePanelChart(chart, params, panelEntries) {
    if (!chart) return chart;
    const localState = Object.fromEntries(panelEntries);
    if (chart.type === "portfolioCagrBars") {
      const selectedPortfolios = params.getAll("portfolios");
      const returnMode = localState.return_mode || chart.returnMode || "average";
      const rollingWindow = Number(params.get(chart.windowParam || "rolling_window")) || 10;
      return {
        ...chart,
        rollingWindow,
        returnMode,
        portfolioOrder: selectedPortfolios.length ? selectedPortfolios : chart.portfolioOrder,
        captionLines: chart.autoCaption === false
          ? chart.captionLines
          : portfolioCagrCaptionLines(params.get("value_mode") || "cpi_il", returnMode, rollingWindow)
      };
    }
    return chart;
  }

