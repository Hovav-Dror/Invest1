  function rowNearestAge(rows, age) {
    return rows.reduce((best, row) => {
      const rowAge = numericValue(row.age);
      if (rowAge === null) return best;
      if (!best) return row;
      return Math.abs(rowAge - age) < Math.abs(numericValue(best.age) - age) ? row : best;
    }, null);
  }

