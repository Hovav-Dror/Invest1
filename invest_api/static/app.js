  function stateFromForm() {
    const state = {};
    const data = new FormData(els.controls);
    data.forEach((value, key) => {
      value = normalizeInputValue(key, value);
      if (state[key]) {
        state[key] = `${state[key]},${value}`;
      } else {
        state[key] = value;
      }
    });
    activeView.controls.filter((control) => control.kind === "checkbox").forEach((control) => {
      state[control.name] = document.getElementById(`control-${control.name}`).checked ? "true" : "false";
    });
    const startMonth = state.start_month;
    const endMonth = state.end_month;
    if (startMonth !== undefined && endMonth !== undefined) {
      const start = Number(startMonth);
      const end = Number(endMonth);
      state.start = monthDate(Math.min(start, end));
      state.end = monthDate(Math.max(start, end));
      delete state.start_month;
      delete state.end_month;
    }
    return state;
  }

