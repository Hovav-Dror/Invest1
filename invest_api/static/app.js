  function formatPercent(value, maximumFractionDigits = 2) {
    if (!Number.isFinite(value)) return "";
    return value.toLocaleString(undefined, { style: "percent", maximumFractionDigits });
  }

  function formatTooltipNumber(value, maximumFractionDigits = 1) {
    if (!Number.isFinite(value)) return "";
    return `\u200e${value.toLocaleString(undefined, { minimumFractionDigits: maximumFractionDigits, maximumFractionDigits })}\u200e`;
  }

  function formatTooltipPercent(value, maximumFractionDigits = 1) {
    if (!Number.isFinite(value)) return "";
    return `\u200e${value.toLocaleString(undefined, { style: "percent", maximumFractionDigits })}\u200e`;
  }

  function formatNumber(value, digits) {
    if (!Number.isFinite(value)) return "";
    if (digits !== undefined) {
      const text = value.toLocaleString(locale, { maximumFractionDigits: digits });
      return value < 0 ? `\u200e${text}\u200e` : text;
    }
    const abs = Math.abs(value);
    let formatted;
    if (abs < 1 && abs !== 0) formatted = value.toLocaleString(undefined, { maximumFractionDigits: 6 });
    else if (abs >= 1000000) formatted = value.toLocaleString(undefined, { maximumFractionDigits: 0 });
    else if (abs >= 1000) formatted = value.toLocaleString(undefined, { maximumFractionDigits: 0 });
    else formatted = value.toLocaleString(undefined, { maximumFractionDigits: 4 });
    return value < 0 ? `\u200e${formatted}\u200e` : formatted;
  }

  function renderView({ restoreScroll = false } = {}) {
    requestSeq += 1;
    storyCollapseSeq = 0;
    clearTimeout(runTimer);
    lastPayload = null;
    currentChartConfig = null;
    els.afterStory.hidden = true;
    els.afterStory.innerHTML = "";
    els.chart.dataset.view = "";
    releaseChart(els.chart);
    renderNav();
    els.title.textContent = activeView.title;
    document.title = `${activeView.title} · סייר תיקי ההשקעות`;
    els.kicker.textContent = activeView.kicker;
    els.takeaway.textContent = activeView.takeaway || "";
    els.takeaway.hidden = !activeView.takeaway;
    renderStory();
    renderControls();
    urlDefaults = { main: activeView.staticOnly ? [] : mainStateEntries(), panels: new Map(), lazy: [], custom: [] };
    if (pendingUrlState) applyMainState(scoped("", pendingUrlState));
    if (activeView.staticOnly) {
      pendingUrlState = null;
      history.replaceState(null, "", buildHash(activeView.id, []));
    }
    const viewId = activeView.id;
    const run = runActiveView();
    if (restoreScroll) {
      restoreViewScroll(viewId);
      Promise.resolve(run).finally(() => restoreViewScroll(viewId));
    }
  }

  let pendingRun = null;

  /** Debounced recalculation; ``panel`` limits it to one panel of a multi-chart view. */
  function scheduleRun(panel = null) {
    clearTimeout(runTimer);
    if (panel === null || (pendingRun && pendingRun.all)) {
      pendingRun = { all: true };
    } else {
      pendingRun = pendingRun || { panels: new Set() };
      pendingRun.panels.add(panel);
    }
    runTimer = setTimeout(() => {
      const run = pendingRun;
      pendingRun = null;
      runActiveView(run);
    }, 300);
  }

  function panelIndexOf(element) {
    const section = element && element.closest("[data-panel-index]");
    return section ? Number(section.dataset.panelIndex) : null;
  }

