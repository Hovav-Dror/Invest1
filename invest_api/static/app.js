  function panelControlState(section, panel) {
    if (!section || !panel.controls) return [];
    const controls = section.querySelector('[data-role="panel-controls"]');
    if (!controls) return [];
    const entries = [];
    controls.querySelectorAll("input[name], select[name]").forEach((input) => {
      if (!input.name) return;
      if (input.type === "radio" && !input.checked) return;
      if (input.type === "checkbox" && !input.checked) return;
      entries.push([input.name, input.value]);
    });
    const portfolioValues = entries.filter(([key]) => key === "portfolios").map(([, value]) => value);
    if (portfolioValues.length) {
      for (let index = entries.length - 1; index >= 0; index -= 1) {
        if (entries[index][0] === "portfolios") entries.splice(index, 1);
      }
      entries.push(["portfolios", portfolioValues.join(",")]);
    }
    const start = entries.find(([key]) => key === "year_start");
    const end = entries.find(([key]) => key === "year_end");
    if (start && end && Number(start[1]) > Number(end[1])) {
      start[1] = end[1];
    }
    return entries;
  }

  function appendPanelParam(params, key, value) {
    if (key === "portfolios") {
      params.delete(key);
      String(value).split(",").map((part) => part.trim()).filter(Boolean).forEach((part) => params.append(key, part));
      return;
    }
    params.set(key, value);
  }

  function updatePanelControlUi(root) {
    root.querySelectorAll("[data-panel-slider]").forEach((slider) => {
      const input = slider.querySelector("input[type='range']");
      const output = slider.querySelector("output");
      if (input && output) {
        const min = Number(input.min);
        const max = Number(input.max);
        const span = max - min || 1;
        const percent = ((Number(input.value) - min) / span) * 100;
        output.textContent = input.value;
        output.style.left = `${percent}%`;
      }
    });
    root.querySelectorAll("[data-panel-range-pair]").forEach((wrap) => {
      const inputs = [...wrap.querySelectorAll("input[type='range']")];
      if (inputs.length !== 2) return;
      const [start, end] = inputs;
      if (Number(start.value) > Number(end.value)) {
        if (document.activeElement === start) end.value = start.value;
        else start.value = end.value;
      }
      const min = Number(start.min);
      const max = Number(start.max);
      const span = max - min || 1;
      const startOutput = wrap.querySelector('[data-range-output="start"]');
      const endOutput = wrap.querySelector('[data-range-output="end"]');
      const lowPercent = ((Number(start.value) - min) / span) * 100;
      const highPercent = ((Number(end.value) - min) / span) * 100;
      if (startOutput) {
        startOutput.textContent = start.value;
        startOutput.style.left = `${lowPercent}%`;
      }
      if (endOutput) {
        endOutput.textContent = end.value;
        endOutput.style.left = `${highPercent}%`;
      }
      wrap.style.setProperty("--range-start", `${lowPercent}%`);
      wrap.style.setProperty("--range-end", `${highPercent}%`);
      const tracks = wrap.querySelector(".date-range-tracks");
      if (tracks) {
        tracks.style.setProperty("--range-start", `${lowPercent}%`);
        tracks.style.setProperty("--range-end", `${highPercent}%`);
        tracks.classList.toggle("labels-overlap", highPercent - lowPercent < 14);
      }
    });
    updatePanelPickerUi(root);
  }

  function updatePanelPickerUi(root) {
    const pickers = root.matches && root.matches(".panel-picker")
      ? [root]
      : [...root.querySelectorAll(".panel-picker")];
    pickers.forEach((picker) => {
      const checked = [...picker.querySelectorAll("input[type='checkbox']:checked")].map((input) => input.value);
      const summary = picker.querySelector("[data-picker-summary]");
      if (summary) summary.textContent = checked.join(", ") || "בחרו תיקים";
      filterPanelPickerOptions(picker);
    });
  }

  function filterPanelPickerOptions(picker) {
    const search = picker.querySelector("[data-picker-search]");
    const query = normalizePickerText(search ? search.value : "");
    const labels = [...picker.querySelectorAll("[data-picker-options] label")];
    let visibleCount = 0;
    labels.forEach((label) => {
      const text = normalizePickerText(label.textContent || "");
      const visible = !query || text.includes(query);
      label.hidden = !visible;
      if (visible) visibleCount += 1;
    });
    const empty = picker.querySelector("[data-picker-empty]");
    if (empty) empty.hidden = visibleCount > 0;
  }

