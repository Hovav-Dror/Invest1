      color: (value) => heatColor(value, limit),
      legend: {
        min: -limit,
        max: limit,
        minLabel: `${chartConfig.negativeLabel} +${formatPercent(limit, 0)}`,
        maxLabel: `${chartConfig.positiveLabel} +${formatPercent(limit, 0)}`
      },
